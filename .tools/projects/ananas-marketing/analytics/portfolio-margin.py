#!/usr/bin/env python3
"""Маржа клиентского портфеля агентства по методу ёмкости контура.

Метод → agency/finmodel.md, раздел «Как считать прямую себестоимость на окладах».
Себестоимость единицы = оклад / ёмкость контура. Незанятая мощность считается
простоем отдельной строкой и НЕ размазывается по клиентам.

Контур Володи считается по ВМЕНЁННОЙ ставке: он не берёт оклад из агентства,
но его работа — не бесплатный ресурс. Ставка = стоимость заменяющего маркетолога
(80-100к, agency/hypotheses.md), ёмкость = 2 проекта (life/decisions.md).
Без этого консалтинг выглядит выручкой с нулевой себестоимостью, и модель
советует продавать именно то, что не масштабируется.

Вход — срез месяца ниже: чеки из листа оплат, исполнители из листа ответственных.
Обновляется руками при новом срезе; источники перечислены в clients/_index.md.

Запуск: .tools/venv/Scripts/python.exe .tools/projects/ananas-marketing/analytics/portfolio-margin.py
"""

MONTH = "сентябрь 2026"

# Контуры: оклад и ёмкость в проектах. Ёмкости подтверждены 2026-09-03.
CONTOURS = {
    "Лия":    {"оклад": 70_000, "ёмкость": 12, "вменённый": False},
    "Юля":    {"оклад": 70_000, "ёмкость": 12, "вменённый": False},
    "Софья":  {"оклад": 45_000, "ёмкость": 30, "вменённый": False},
    "Володя": {"оклад": 90_000, "ёмкость": 2,  "вменённый": True},
}

TAXES = 25_258      # налоги Владимир, ДДС сен26
BANK_FEE = 950      # комиссия Точки

# (клиент, чек, [окладные исполнители], доля переменного исполнителя)
# Софья добавляется в исполнители как account там, где ведёт клиента.
CLIENTS = [
    ("Левша",                150_000, ["Володя", "Лия"],   0.0),
    ("Клипин · Стиралкин",    80_000, ["Володя", "Софья"], 0.0),
    ("Unisec",                50_000, ["Володя", "Софья"], 0.0),
    ("Калифорния",            43_181, ["Софья"],           0.40),  # Света, 40% от чека
    ("Ковалевский · Енот",    38_000, ["Юля", "Софья"],    0.0),
    ("Шмыкова · FunCleaning", 36_000, ["Юля", "Софья"],    0.0),
    ("Вдовин",                30_000, ["Лия", "Софья"],    0.0),
    ("Филичев",               30_000, ["Лия", "Софья"],    0.0),
    ("Евсеев",                30_000, ["Лия", "Софья"],    0.0),
    ("Прохоров",              30_000, ["Лия", "Софья"],    0.0),
    ("Панкратьев · Бинго",    25_000, ["Юля", "Софья"],    0.0),
    ("Жуков",                 25_000, ["Лия", "Софья"],    0.0),
    ("Сивков",                20_000, ["Юля", "Софья"],    0.0),
    ("Шек",                   20_000, ["Юля", "Софья"],    0.0),
    ("Де Виллер",             18_000, ["Юля", "Софья"],    0.0),
    ("Галимов",               15_000, ["Лия", "Софья"],    0.0),
    ("Соловьева",             15_000, ["Лия", "Софья"],    0.0),
    ("Исаков",                15_000, ["Лия", "Софья"],    0.0),
    ("Родионов · Сиверко",    13_000, ["Юля", "Софья"],    0.0),
    ("Царегородцева · Cleo",  10_000, ["Юля", "Софья"],    0.0),
    ("magister tg",                0, [],                  0.40),  # работа за кейс
]


def money(x):
    return f"{x:>10,.0f}".replace(",", " ")


def main():
    unit = {k: v["оклад"] / v["ёмкость"] for k, v in CONTOURS.items()}
    занято = {k: 0 for k in CONTOURS}
    for _, _, исполнители, _ in CLIENTS:
        for и in исполнители:
            занято[и] += 1

    print(f"\nМаржа портфеля — {MONTH}\n")
    print(f"{'Контур':<9}{'оклад':>9}{'занято':>9}{'ёмкость':>9}{'единица':>10}{'простой':>11}")
    print("-" * 57)
    простой_всего = перегруз = 0
    for k, v in CONTOURS.items():
        idle = v["оклад"] - unit[k] * занято[k]
        метка = ""
        if idle < 0:
            перегруз += -idle
            метка = "  ПЕРЕГРУЗ"
        elif not v["вменённый"]:
            простой_всего += idle
        print(f"{k:<9}{money(v['оклад'])}{занято[k]:>9}{v['ёмкость']:>9}"
              f"{money(unit[k])}{money(idle)}{метка}")
    print("\nОклад Володи вменённый: он его не получает, но контур занимает мощность.")

    print(f"\n{'Клиент':<24}{'чек':>10}{'исполнение':>12}{'вклад':>11}{'%':>7}")
    print("-" * 66)
    выручка = вклад_всего = 0
    for имя, чек, исполнители, переменный in CLIENTS:
        c = sum(unit[и] for и in исполнители) + чек * переменный
        вклад = чек - c
        выручка += чек
        вклад_всего += вклад
        доля = f"{вклад / чек * 100:>6.0f}%" if чек else "     —"
        print(f"{имя:<24}{money(чек)}{money(c)}{'':>2}{money(вклад)}{доля}")

    print("-" * 66)
    print(f"{'Итого':<24}{money(выручка)}{'':>12}{money(вклад_всего)}")

    вменённый = sum(unit[k] * занято[k] for k, v in CONTOURS.items() if v["вменённый"])
    касса = вклад_всего + вменённый - простой_всего - TAXES - BANK_FEE
    эконом = вклад_всего - простой_всего - TAXES - BANK_FEE

    print(f"\n{'Вклад клиентов':<34}{money(вклад_всего)}")
    print(f"{'− простой мощности':<34}{money(-простой_всего)}")
    print(f"{'− налоги и комиссия':<34}{money(-TAXES - BANK_FEE)}")
    print(f"{'= экономический остаток':<34}{money(эконом)}   маржа {эконом / выручка * 100:.0f}%")
    print(f"{'+ вменённая ставка Володи':<34}{money(вменённый)}")
    print(f"{'= кассовый остаток':<34}{money(касса)}   маржа {касса / выручка * 100:.0f}%")
    print("\nКассовый — что реально остаётся сейчас. Экономический — что останется,")
    print("когда работу Володи будет делать наёмный маркетолог. Разница и есть цена")
    print("делегируемости: пока она не закрыта, 1 млн чистыми считается по кассовой цифре,")
    print("а строится по экономической.")

    порог = unit["Лия"] + unit["Софья"]
    print(f"\nПол цены строки: единица исполнения + account = {порог:,.0f} ₽.".replace(",", " "))
    print()


if __name__ == "__main__":
    main()
